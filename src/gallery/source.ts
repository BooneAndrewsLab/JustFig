/**
 * "Save as template" (note 08): a figure, or a selection, written out as the
 * TypeScript source of a `GalleryEntry`, for a contributor to drop into
 * `src/gallery/` and register in `GALLERY`.
 *
 * The objects are emitted as literal data, not as factory calls: a drawn
 * figure's objects carry every field the editor set (names, frames, styles,
 * text runs, bindings), and a factory call per object would either lose some
 * or restate them all. The literal is typed (`Obj[]`), so the compiler checks
 * it against the current schema, and the entry rebuilds it through
 * `templateFigure` with fresh ids. Arrows keep their attachments; icons keep
 * their asset (SVG and licence meta) in the entry, so it builds offline.
 *
 * The data blocks are marked `prettier-ignore`, so the file passes the
 * repo's format check as generated.
 */
import type { Figure, Obj, Page } from '@/core/model/types';
import { assetsUsed } from '@/io/presets';

export interface TemplateSpec {
  /** Kebab-case, as gallery ids are. */
  readonly id: string;
  readonly title: string;
  readonly description: string;
  readonly kind: 'template' | 'example';
}

export const TEMPLATE_ID = /^[a-z0-9]+(-[a-z0-9]+)*$/;

/** The id as a file name stem and as an identifier. */
export const templateFileName = (id: string): string => `${id}.ts`;

export function templateIdentifier(id: string): string {
  const camel = id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  return /^[0-9]/.test(camel) ? `entry${camel.charAt(0).toUpperCase()}${camel.slice(1)}` : camel;
}

/** A single-quoted TypeScript string literal. */
function quote(s: string): string {
  const body = s
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/[\u2028\u2029]/g, (c) => `\\u${c.charCodeAt(0).toString(16)}`);
  return `'${body}'`;
}

/** `  key: 'value',` as Prettier lays it out: the value drops a line when it does not fit. */
function property(key: string, value: string): string {
  const one = `  ${key}: ${value},`;
  return one.length <= 100 ? one : `  ${key}:\n    ${value},`;
}

const json = (v: unknown): string => JSON.stringify(v, null, 2);

/**
 * The objects a template would hold: the selection when there is one,
 * else everything on the page, layers in order.
 */
export function templateObjects(page: Page, selection: readonly Obj[]): Obj[] {
  return selection.length > 0 ? [...selection] : page.layers.flatMap((l) => l.children);
}

/** The source of the entry. */
export function templateSource(
  fig: Figure,
  page: Page,
  objects: readonly Obj[],
  spec: TemplateSpec,
): string {
  if (!TEMPLATE_ID.test(spec.id)) throw new Error('The id must be lowercase words joined by -.');
  if (objects.length === 0) throw new Error('There is nothing to save.');
  const { id: _doc, pages: _pages, ...doc } = fig.doc;
  const { id: _page, layers: _layers, ...pageSettings } = page;
  const assets = assetsUsed(objects, fig.assets);
  return [
    '/**',
    ` * ${spec.title.replace(/\*\//g, '* /').replace(/\s+/g, ' ')}: generated by Save as template (note 08).`,
    ' * Register it in `GALLERY` in `gallery.ts`, then add a line to docs/guide/10-templates.md.',
    ' */',
    "import type { Assets, Obj } from '@/core/model/types';",
    '',
    "import type { GalleryEntry } from './gallery';",
    "import { type TemplateDoc, type TemplatePage, templateFigure } from './kit';",
    '',
    '// prettier-ignore',
    `const DOC: TemplateDoc = ${json(doc)};`,
    '',
    '// prettier-ignore',
    `const PAGE: TemplatePage = ${json(pageSettings)};`,
    '',
    '// prettier-ignore',
    `const OBJECTS: readonly Obj[] = ${json(objects)};`,
    '',
    '// prettier-ignore',
    `const ASSETS: Assets = ${json(assets)};`,
    '',
    `export const ${templateIdentifier(spec.id)}: GalleryEntry = {`,
    `  id: ${quote(spec.id)},`,
    property('title', quote(spec.title)),
    property('description', quote(spec.description)),
    `  kind: ${quote(spec.kind)},`,
    '  build: () => templateFigure(DOC, PAGE, OBJECTS, ASSETS),',
    '};',
    '',
  ].join('\n');
}
